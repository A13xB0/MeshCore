#!/usr/bin/env python3
"""Generate web_assets.h from the files in examples/meshos_repeater/web/.

The MeshOS repeater serves two embedded pages:
  * index.html        - the MeshOS dashboard SPA, stored verbatim (served as-is)
  * update.html.gz     - the ElegantOTA /update page, stored gzip-compressed and
                         served with Content-Encoding: gzip

Both are emitted as byte arrays so the compiled firmware embeds the exact bytes
that were extracted from the shipped binary. Keeping these as data files (not
baked into a header in the repo) means the only thing left to reproduce for a
byte-identical firmware is the compiled code.

Usage:
    python3 tools/embed_web.py \
        examples/meshos_repeater/web \
        examples/meshos_repeater/web_assets.h
"""
import sys
from pathlib import Path


def emit_array(name: str, data: bytes) -> str:
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("  " + "".join(f"0x{b:02x}," for b in chunk))
    lines.append("};")
    lines.append(f"static const unsigned int {name}_len = {len(data)};")
    return "\n".join(lines)


def main() -> int:
    web_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("examples/meshos_repeater/web")
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else web_dir.parent / "web_assets.h"

    index_html = (web_dir / "index.html").read_bytes()
    update_gz = (web_dir / "update.html.gz").read_bytes()

    # index.html is served as a C string in the original, so keep its NUL terminator
    if not index_html.endswith(b"\x00"):
        index_html = index_html + b"\x00"

    parts = [
        "// Generated by tools/embed_web.py - do not edit by hand.",
        "// Source: examples/meshos_repeater/web/",
        "#pragma once",
        "",
        emit_array("INDEX_HTML", index_html),
        "",
        emit_array("UPDATE_HTML_GZ", update_gz),
        "",
    ]
    out.write_text("\n".join(parts))
    print(f"wrote {out} ({out.stat().st_size} bytes): "
          f"INDEX_HTML={len(index_html)} UPDATE_HTML_GZ={len(update_gz)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
